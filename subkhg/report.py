#!/usr/bin/env python3
"""Write a markdown report of a real-data run from its output folders, so the numbers can be regenerated.

  python -m subkhg.report --subkhg-config ../re-peat/sites/kampar_gaung/subkhg.yaml \\
      --neraca-config ../re-peat/sites/kampar_gaung/neraca_experiments.yaml --out ../re-peat/sites/kampar_gaung/reports/kampar_gaung.md

Reads the outputs of repeat_delineation, repeat_neraca.bucket.run (and repeat_neraca.bucket.covariates if it was run) and subkhg.run.
The report states facts and numbers only; what they mean and the decisions taken are in the run's runbook.
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

from common import pipeline
from subkhg.run import PRESET as SUBKHG_PRESET


def rho(a, b):
    a, b = pd.Series(a, dtype=float), pd.Series(b, dtype=float)
    ok = a.notna() & b.notna()
    if ok.sum() < 4 or a[ok].nunique() < 2 or b[ok].nunique() < 2:
        return None
    return round(float(spearmanr(a[ok], b[ok]).correlation), 2)


def f2(x, nd=2):
    return "n/a" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{nd}f}"


def table(rows, header):
    return ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--subkhg-config", required=True)
    ap.add_argument("--neraca-config", required=True)
    ap.add_argument("--out", required=True, help="markdown file to write; the calibration figure is copied next to it")
    a = ap.parse_args(argv)
    sc = pipeline.load_config(a.subkhg_config, SUBKHG_PRESET, "subkhg")
    nc = pipeline.load_config(a.neraca_config, {}, "neraca")
    out_md = Path(a.out)
    out_md.parent.mkdir(parents=True, exist_ok=True)
    md = [f"# Run report: {out_md.stem}", "",
          f"Generated by `python -m subkhg.report --subkhg-config {a.subkhg_config} --neraca-config {a.neraca_config}` "
          "from the output folders of the run. Numbers only; decisions and their reasons are in the runbook.", ""]

    # ---- sub-KHG units
    import geopandas as gpd
    up = Path(sc["units"]["path"])
    if up.exists():
        g = gpd.read_file(up)
        c = g.geometry.union_all().centroid
        from repeat_common.grid import auto_utm
        area = g.to_crs(auto_utm(c.x, c.y)).area / 1e6
        md += ["## 1. Sub-KHG", "", f"- {len(g)} sub-KHG from `{up}`; area (km2) min {area.min():.0f}, median {area.median():.0f}, max {area.max():.0f}, "
               f"total {area.sum():,.0f}", ""]
    # ---- neraca air
    nd = Path(nc["out"])
    rep = json.load(open(nd / "neraca_report.json", encoding="utf-8")) if (nd / "neraca_report.json").exists() else None
    if rep:
        k = rep["khg"][0]
        cal = k["calibration"]
        v = cal["verdict"]
        md += ["## 2. Neraca air against SiTMAT stations", "",
               f"- Stations inside the KHG: {cal['n_stations']} ({cal['period'][0]} to {cal['period'][1]}); peat depth filled by the KHG median for {cal['n_stations_peat_depth_filled']}",
               f"- Fitted on all stations: Sy {cal['fitted']['sy']}, k {cal['fitted']['k']} mm/day, z0 {cal['fitted']['z0']} cm "
               f"(grids: Sy up to {max(rep['config']['sy_grid'])}, k up to {max(rep['config']['k_grid'])}, z0 up to {max(rep['config']['z0_grid'])}; a value at the upper end means the fit hit the edge of the grid)",
               f"- Drainage term kept: {cal['drainage_kept']} (out-of-fold RMSE gain {100 * cal['drainage_gain_share']:.0f}%)",
               f"- **Verdict: usable for ranking = {v['usable_for_ranking']}**" + (f" ({v['reason']})" if v["reason"] else ""), "",
               "Scored on stations in spatial blocks that were left out of the fit:", ""]
        rows = []
        for name in ("with_drainage", "without_drainage"):
            x = cal[name]
            rows.append([name.replace("_", " "), f2(x["rmse_cm"], 1), f2(x["rmse_baseline_cm"], 1), f2(x["temporal_r_median"]),
                         f"{f2(x['temporal_r_q25_q75'][0])} to {f2(x['temporal_r_q25_q75'][1])}" if x["temporal_r_q25_q75"] else "n/a",
                         f2(x["spatial_spearman_peak"]), f2(x["spatial_spearman_days_gt40"]), f2(x["peak_rmse_cm"], 1), f2(x["peak_rmse_baseline_cm"], 1)])
        md += table(rows, ["model", "RMSE cm", "baseline RMSE cm", "temporal r (median)", "temporal r (IQR)",
                           "spatial rho peak", "spatial rho days>40", "peak RMSE cm", "baseline peak RMSE cm"])
        md += ["", "Baseline: every station follows the mean observed curve of the stations used for the fit. "
               "Temporal r is the per-station correlation of the daily series; spatial rho is across stations.", "",
               "Single covariates on their own (Spearman with the observed value): " +
               ", ".join(f"{kk} {f2(vv)}" for kk, vv in cal["covariates_alone"].items()), ""]
        cov = nd / "neraca_covariates.md"
        if cov.exists():
            md += [cov.read_text(encoding="utf-8").replace("# Station covariates", "### Station covariates"), ""]
        png = nd / "neraca_calibration.png"
        if png.exists():
            shutil.copy(png, out_md.parent / f"{out_md.stem}_neraca_calibration.png")
            md += [f"![neraca air against stations]({out_md.stem}_neraca_calibration.png)", ""]
        md += ["### Spread of each output across the sub-KHG", ""]
        rows = [[c, f2(s["min"]), f2(s["median"]), f2(s["max"]), f2(s["spearman_with_peat_depth"]), f2(s["spearman_with_canal_proximity"])]
                for c, s in k["spread_across_sub_khg"].items()]
        md += table(rows, ["output", "min", "median", "max", "rho with mean peat depth", "rho with canal proximity"]) + [""]

    # ---- ranking
    od = Path(sc["out"])
    if (od / "laporan.json").exists():
        lap = json.load(open(od / "laporan.json", encoding="utf-8"))
        d = pd.read_csv(od / "unit_prioritas.csv")
        md += ["## 3. Sub-KHG ranking", "", f"- {len(d)} sub-KHG; method that sets `kelas` and `peringkat`: **{lap.get('method')}**",
               f"- Indicators scored in the need score: {', '.join(lap['indicators_used'])}",
               f"- Rank-sum indicators used: {', '.join(lap['ranksum']['used'])}; not available: {', '.join(lap['ranksum']['missing']) or 'none'}",
               f"- Classes: " + "; ".join(f"{k}: {v}" for k, v in lap["class_counts"].items()),
               f"- Agreement of the two methods: {lap.get('ranking_agreement')}",
               "- Strongly correlated indicator pairs: " + (", ".join(f"{p['a']}/{p['b']} ({p['spearman']})" for p in lap.get("correlated_pairs", [])) or "none"), ""]
        if "neraca_skill_ok" in d:
            md += [f"- `neraca_skill_ok` of the merged neraca air columns: {int(d['neraca_skill_ok'].iloc[0])} (0 = failed the skill check)", ""]
        md += ["### Indicator values across the sub-KHG (raw)", ""]
        cols = ["i_peat_depth", "f_reach", "u_canal_density", "n_sekat_ada", "n_sekat_perlu", "sekat_tambahan", "m_ipg", "kemiringan_kanal",
                "u_ndmi", "u_ndvi", "u_fire_freq", "u_hotspot", "i_forest", "f_water_dist", "f_lift", "u_tma", "n_tma_stations",
                "u_wb_daily_mean", "u_storage_decline_pct", "u_wt_days_gt40"]
        rows = [[c, int(d[c].notna().sum()), f2(d[c].min(), 3), f2(d[c].median(), 3), f2(d[c].max(), 3)] for c in cols if c in d]
        md += table(rows, ["column", "units with a value", "min", "median", "max"]) + [""]
        if "n_sekat_ada" in d:
            md += [f"Canal blocks counted: existing {int(d.n_sekat_ada.sum())}, needed by the spacing rule {int(d.n_sekat_perlu.sum())}.", ""]
        p = sc["params"]
        if "kemiringan_kanal" in d and d["kemiringan_kanal"].notna().any():
            sl = d["kemiringan_kanal"].dropna()
            cap = float(p["ipg_dA_m"]) / float(p["ipg_js_max_m"])           # slope below this puts the block spacing at its maximum
            q = np.percentile(sl, [0, 25, 50, 75, 100])
            md += ["### Canal slope and block spacing (metrik IPG)", "",
                   f"- Median canal slope per sub-KHG, from the DTM: min / 25% / median / 75% / max = " + " / ".join(f"{x:.5f}" for x in q),
                   f"- Block spacing is dA / slope with dA = {p['ipg_dA_m']} m, kept between {p['ipg_js_min_m']} and {p['ipg_js_max_m']} m. "
                   f"A slope below {cap:.5f} gives the maximum spacing: **{int((sl < cap).sum())} of {len(sl)} sub-KHG** are at that cap, "
                   "so for them the number of blocks needed is the canal length divided by the maximum spacing, not a result of the terrain.", ""]
        if "i_peat_depth" in d:
            floor = float(d["i_peat_depth"].min())
            md += [f"Sub-KHG whose mean peat depth is within 2 cm of the lowest value ({floor:.2f} m, the raster floor): "
                   f"{int((d['i_peat_depth'] < floor + 0.02).sum())} of {int(d['i_peat_depth'].notna().sum())}.", ""]
        md += ["### Rank agreement with single indicators (Spearman)", ""]
        rows = []
        for c in ("u_ndmi", "u_ndvi", "i_peat_depth", "i_forest", "f_reach", "f_water_dist", "u_hotspot", "u_storage_decline_pct", "u_wt_days_gt40"):
            if c in d:
                rows.append([c, f2(rho(d.skor_need, d[c])), f2(rho(d.skor_ranksum_need, d[c])) if "skor_ranksum_need" in d else "n/a"])
        md += table(rows, ["indicator", "need score", "rank-sum score"]) + [""]
        top = d.sort_values("peringkat").head(10)[["unit_id", "kelas", "peringkat", "peringkat_need", "peringkat_ranksum", "area_km2"]]
        md += ["### Top 10 by the method in use", ""] + table(
            [[r.unit_id, r.kelas, int(r.peringkat), int(r.peringkat_need), int(r.peringkat_ranksum), f"{r.area_km2:.0f}"] for r in top.itertuples()],
            ["unit", "class", "rank", "rank by need score", "rank by rank-sum", "km2"]) + [""]
    text = "\n".join(md)
    out_md.write_text(text + "\n", encoding="utf-8")
    print(f"written {out_md} ({len(md)} lines)")


if __name__ == "__main__":
    main()
