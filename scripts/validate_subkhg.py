#!/usr/bin/env python3
"""Held-out validation of the sub-KHG ranking: does a ranking built on earlier years point at the units that burned later?

  python scripts/validate_subkhg.py --config ../re-peat/sites/14.02-04-05.01_kampar_gaung/subkhg.yaml \
      --config ../re-peat/sites/16.02.01_sugihan_lumpur/subkhg.yaml --out ../re-peat/reports/subkhg_validation.md

Folds (both El Nino dry seasons): indicators 2015-2018, test 2019; indicators 2015-2022, test 2023. For each site config and fold
the ranking is rerun (`subkhg.run --skip-fetch`) with that baseline and validation year into
`<site out>/validation/<fold>/`; the derived config is written there too. This year's KLH hotspots (u_hotspot_now) get weight 0
in the folds: they come after the test years (AGENTS.md). Indicators without data in a fold's years drop out of that fold
(for example NDMI, cached for 2019-2021 only, in the 2015-2018 fold).

Targets: burned share of the unit's peat in the test year (`v_burned_frac`) and hotspots per km2 of peat (`v_hotspot`), from the
national layers. With 20-30 units and small burns, a fixed burn threshold leaves few or no positive units, so the test is
continuous: Spearman between score and target, with a 90 % bootstrap interval over units (2,000 resamples), for the need score,
its urgency part, fire history alone (u_fire_freq) and the rank-sum. A score earns its other indicators only if it beats fire
history alone. Also: share of the target in the top 20 % of units by score (random: 20 %).
"""
import argparse
import copy
import json
from pathlib import Path

import numpy as np
import pandas as pd
import yaml
from scipy.stats import spearmanr

FOLDS = {"2015-2018_to_2019": ([2015, 2018], [2019]), "2015-2022_to_2023": ([2015, 2022], [2023])}
SCORES = {"skor_risiko": "need score", "skor_urgensi": "urgency part", "u_fire_freq": "fire history alone", "skor_ranksum_need": "rank-sum"}


def boot_rho(s, t, n=2000, seed=0):
    ok = np.isfinite(s) & np.isfinite(t)
    s, t = s[ok], t[ok]
    if len(s) < 5 or np.std(s) == 0 or np.std(t) == 0:
        return np.nan, np.nan, np.nan, len(s)
    rng = np.random.default_rng(seed)
    r = [spearmanr(s[i], t[i]).correlation for i in (rng.integers(0, len(s), len(s)) for _ in range(n))]
    r = np.array(r, float)
    return float(spearmanr(s, t).correlation), float(np.nanquantile(r, 0.05)), float(np.nanquantile(r, 0.95)), len(s)


def capture(s, t, a, q=0.2):
    ok = np.isfinite(s) & np.isfinite(t)
    s, t, a = s[ok], t[ok], a[ok]
    tot = np.sum(t * a)
    return float(np.sum((t * a)[s >= np.quantile(s, 1 - q)]) / tot) if tot > 0 else np.nan


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", action="append", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    from repeat_prioritisation.common import pipeline
    from repeat_prioritisation.subkhg import run as R
    L = ["# Sub-KHG ranking: held-out validation", "",
         "Generated by `scripts/validate_subkhg.py`. Spearman between the score and the test-year target across units, with a 90 % "
         "bootstrap interval; capture = share of the target in the top 20 % of units by score (random 20 %). "
         "Indicators from 2015 to the year before the test; this year's hotspots excluded. Weights are provisional.", ""]
    rows = []
    for cpath in a.config:
        raw = yaml.safe_load(Path(cpath).read_text(encoding="utf-8"))
        base_out = Path(pipeline.load_config(cpath, R.PRESET, "subkhg")["out"])
        for fold, (yb, yv) in FOLDS.items():
            c = copy.deepcopy(raw)
            c["years"] = {**(c.get("years") or {}), "baseline": yb, "validation": yv}
            c.setdefault("indicators", {})["u_hotspot_now"] = {"weight": 0.0}
            od = base_out / "validation" / fold
            od.mkdir(parents=True, exist_ok=True)
            cf = od / "config.yaml"
            cf.write_text(yaml.safe_dump(c, sort_keys=False, allow_unicode=True), encoding="utf-8")
            R.main(["--config", str(cf), "--skip-fetch", "--out", str(od)])
            d = pd.read_csv(od / "unit_prioritas.csv")
            used = json.load(open(od / "laporan.json", encoding="utf-8"))["indicators_used"]
            area = d["area_km2"].to_numpy(float)
            for tgt in ("v_burned_frac", "v_hotspot"):
                t = d[tgt].to_numpy(float)
                for sc, label in SCORES.items():
                    if sc not in d:
                        continue
                    rho, lo, hi, n = boot_rho(d[sc].to_numpy(float), t)
                    rows.append({"site": Path(cpath).parent.name, "fold": fold, "target": tgt, "score": label, "units": n,
                                 "units_with_target": int((t > 0).sum()), "rho": rho, "lo": lo, "hi": hi,
                                 "capture_top20": capture(d[sc].to_numpy(float), t, area), "indicators": ", ".join(used)})
    r = pd.DataFrame(rows)
    r.to_csv(Path(a.out).with_suffix(".csv"), index=False, float_format="%.3f")
    for (site, fold), g in r.groupby(["site", "fold"], sort=False):
        L += [f"## {site}, {fold.replace('_to_', ', test ')}", "", f"Need-score indicators: {g['indicators'].iloc[0]}.", "",
              "| target | score | units (with target > 0) | Spearman (90 % interval) | capture top 20 % |", "|---|---|---|---|---|"]
        for x in g.itertuples():
            L.append(f"| {x.target} | {x.score} | {x.units} ({x.units_with_target}) | {x.rho:.2f} ({x.lo:.2f} to {x.hi:.2f}) | {x.capture_top20:.0%} |")
        L.append("")
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
